use proc_macro2::TokenStream;
use quote::quote;
use rs_lvgl_codegen::{CodeGen, Rusty};
use std::env;
use std::fs::File;
use std::io::prelude::*;
use std::path::PathBuf;

fn main() {
    let out_path = PathBuf::from(env::var("OUT_DIR").unwrap());
    let rs = out_path.join("generated.rs");

    // Generate from the bindings of the rs_lvgl_sys this crate links against.
    // The build-dependency copy is compiled with its own features and may
    // have a different widget set (`minimal-config`).
    println!("cargo:rerun-if-env-changed=DEP_LVGL_BINDINGS");
    let widgets_impl = match env::var("DEP_LVGL_BINDINGS") {
        Ok(path) => {
            println!("cargo:rerun-if-changed={path}");
            std::fs::read_to_string(&path).expect("read rs_lvgl_sys bindings")
        }
        Err(_) => rs_lvgl_sys::_bindgen_raw_src().to_string(),
    };

    // `lv_use_<widget>` for every optional widget the linked config enables.
    let enabled = env::var("DEP_LVGL_WIDGETS").unwrap_or_default();
    let optional = env::var("DEP_LVGL_OPTIONAL_WIDGETS").unwrap_or_default();
    for name in optional.split(',').filter(|s| !s.is_empty()) {
        let name = name.replace('-', "_");
        println!("cargo:rustc-check-cfg=cfg(lv_use_{name})");
    }
    for name in enabled.split(',').filter(|s| !s.is_empty()) {
        let name = name.replace('-', "_");
        println!("cargo:rustc-cfg=lv_use_{name}");
    }

    let codegen = CodeGen::from(&widgets_impl).unwrap();
    let widgets_impl: Vec<TokenStream> = codegen
        .get_widgets()
        .iter()
        .flat_map(|w| w.code(&()))
        .collect();

    let code = quote! {
        #(#widgets_impl)*
    };

    let mut file = File::create(rs).unwrap();
    writeln!(
        file,
        "/* automatically generated by rs_lvgl_codegen */\n{}",
        code
    )
    .unwrap();
}
